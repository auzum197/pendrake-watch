// Regenerates src/components/app/tx-list/pool-glyphs.ts: the outlines of the four
// pool names in Nunito Sans Variable at weight 400, so the transaction list can
// morph them into discs under Discreet mode. Reads the latin woff2 that the app
// ships through @fontsource-variable, decompresses it (fontkit reads WOFF2 but
// loses the cmap on variation instances, so it goes through TTF), and lays out
// each word with the base font while taking the weight-400 outline of each glyph
// from the variation instance.
//
//   pnpm glyphs

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as fontkit from "fontkit";
import { decompress } from "wawoff2";

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));

const woff2 = require.resolve(
  "@fontsource-variable/nunito-sans/files/nunito-sans-latin-wght-normal.woff2",
);
const out = path.resolve(here, "../src/components/app/tx-list/pool-glyphs.ts");

const NAMES = {
  orchard: "Orchard",
  sapling: "Sapling",
  ironwood: "Ironwood",
  transparent: "Transparent",
};

const ttf = Buffer.from(await decompress(readFileSync(woff2)));
const base = fontkit.create(ttf);
const regular = base.getVariation({ wght: 400 });

const glyphs = {};
for (const [pool, word] of Object.entries(NAMES)) {
  const run = base.layout(word);
  let x = 0;
  const parts = [];
  run.glyphs.forEach((g, i) => {
    const glyph = regular.getGlyph(g.id);
    const pos = run.positions[i];
    const d = glyph.path.translate(x + pos.xOffset, pos.yOffset).scale(1, -1).toSVG();
    if (d) parts.push(d);
    x += glyph.advanceWidth;
  });
  glyphs[pool] = { advance: Math.round(x), d: parts.join(" ") };
}

const font = {
  unitsPerEm: base.unitsPerEm,
  ascent: base.ascent,
  descent: base.descent,
};

const lines = [
  "// Generated by scripts/gen-pool-glyphs.mjs. Do not edit by hand.",
  "//",
  "// Outlines of the four pool names in Nunito Sans Variable at weight 400, in font",
  "// units with y pointing down, laid out with the font's own advances and kerning.",
  "// The transaction list morphs these into discs under Discreet mode.",
  "",
  `export const FONT = ${JSON.stringify(font)};`,
  "",
  "export const POOL_GLYPHS = {",
  ...Object.entries(glyphs).map(
    ([k, v]) => `  ${k}: { advance: ${v.advance}, d: ${JSON.stringify(v.d)} },`,
  ),
  "} as const;",
  "",
];

writeFileSync(out, lines.join("\n"));
console.log(`wrote ${path.relative(process.cwd(), out)}`);
